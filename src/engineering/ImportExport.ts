export function exportJsonPackage(catalog: CatalogSnapshot, diagram?: ErdDocument): string {
  return JSON.stringify(
    {
      format: 'erd-workbench-package',
      version: 1,
      catalog,
      diagram: diagram ?? null,
      note: 'Physical FKs are in catalog. Visual/inferred edges live only on the diagram.',
    },
    null,
    2
  );
}

export function exportSqlDdl(tables: TableMeta[]): string {
  const lines: string[] = ['-- Generated by ERD Workbench', ''];
  for (const t of tables.filter((x) => x.kind === 'table')) {
    const cols = (t.columns ?? [])
      .map((c) => {
        const nullSql = c.isNullable ? 'NULL' : 'NOT NULL';
        const def =
          c.columnDefault !== null && c.columnDefault !== undefined
            ? ` DEFAULT ${formatDefault(c.columnDefault)}`
            : '';
        const extra = c.extra ? ` ${c.extra}` : '';
        return `  \`${c.name}\` ${c.columnType} ${nullSql}${def}${extra}`;
      })
      .join(',\n');
    const pk = t.indexes?.find((i) => i.primary);
    const pkSql = pk ? `,\n  PRIMARY KEY (${pk.columns.map((c) => `\`${c}\``).join(', ')})` : '';
    lines.push(`CREATE TABLE \`${t.schema}\`.\`${t.name}\` (\n${cols}${pkSql}\n);`);
    lines.push('');
  }
  for (const t of tables) {
    for (const fk of t.foreignKeys ?? []) {
      lines.push(
        `ALTER TABLE \`${t.schema}\`.\`${t.name}\` ADD CONSTRAINT \`${fk.name}\` FOREIGN KEY (${fk.columns
          .map((c) => `\`${c}\``)
          .join(', ')}) REFERENCES \`${fk.referencedSchema}\`.\`${fk.referencedTable}\` (${fk.referencedColumns
          .map((c) => `\`${c}\``)
          .join(', ')});`
      );
    }
  }
  return lines.join('\n');
}

export function exportDbml(tables: TableMeta[], visualEdges: DiagramEdge[] = []): string {
  const lines: string[] = ['// Generated by ERD Workbench', '// Physical FKs as Ref; visual/inferred annotated', ''];
  for (const t of tables) {
    lines.push(`Table ${t.schema}.${t.name} {`);
    for (const c of t.columns ?? []) {
      const flags: string[] = [];
      if (c.columnKey === 'PRI') {
        flags.push('pk');
      }
      if (!c.isNullable) {
        flags.push('not null');
      }
      const flagSql = flags.length ? ` [${flags.join(', ')}]` : '';
      lines.push(`  ${c.name} ${c.columnType}${flagSql}`);
    }
    lines.push('}');
    lines.push('');
  }
  for (const t of tables) {
    for (const fk of t.foreignKeys ?? []) {
      const left = fk.columns.map((c) => `${t.schema}.${t.name}.${c}`).join(', ');
      const right = fk.referencedColumns
        .map((c) => `${fk.referencedSchema}.${fk.referencedTable}.${c}`)
        .join(', ');
      lines.push(`Ref: ${left} > ${right}`);
    }
  }
  for (const e of visualEdges.filter((x) => x.relationshipKind !== 'physical')) {
    lines.push(
      `// ${e.relationshipKind}: ${e.sourceTableId}.(${e.sourceColumns.join(',')}) > ${e.targetTableId}.(${e.targetColumns.join(',')})`
    );
  }
  return lines.join('\n');
}

function formatDefault(v: string): string {
  if (/^(-?\d+(\.\d+)?|NULL|CURRENT_TIMESTAMP|TRUE|FALSE)$/i.test(v)) {
    return v;
  }
  return `'${v.replace(/'/g, "''")}'`;
}
